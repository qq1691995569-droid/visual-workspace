import {test,expect} from '@playwright/test'
test('技能图独有工具栏对比，任意两图空格对比且不抢占输入',async({page})=>{
 await page.goto('/')
 const src='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='
 const nodes=['a','b','skill'].map((id,i)=>({id,type:'card',position:{x:120+i*300,y:280},style:{width:200,height:200},data:{kind:'image',src,label:id,comparison:{original:src},...(id==='skill'?{iterationContext:{tool:'light',prompt:'',referenceIds:[],options:{model:'dreo-default',resolution:'2K',ratio:'auto',count:1}},skillResult:{jobId:'done',sourceNode:'removed',review:{}}}:{})}}))
 await page.locator('input[accept=".visproj"]').setInputFiles({name:'pair.visproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'visproj',schemaVersion:1,name:'两图对比',viewport:{x:0,y:0,zoom:1},edges:[],nodes}))})
 await page.locator('[data-id="a"] .image-body').click()
 await expect(page.getByRole('toolbar',{name:'图片快捷修改'}).getByRole('button',{name:'滑块对比'})).toHaveCount(0)
 await page.locator('[data-id="skill"] .image-body').click()
 await expect(page.getByRole('toolbar',{name:'图片快捷修改'}).getByRole('button',{name:'滑块对比'})).toBeVisible()
 await page.locator('[data-id="a"] .image-body').click()
 await page.locator('[data-id="b"] .image-body').click({modifiers:['Shift']})
 await page.keyboard.press('Space')
 const dialog=page.getByRole('dialog',{name:'两张图片滑块对比'})
 await expect(dialog).toBeVisible()
 await dialog.getByRole('slider').fill('75')
 await expect(dialog.getByRole('slider')).toHaveValue('75')
 await dialog.getByRole('button',{name:'交换左右'}).click()
 await expect(dialog.locator('.comparison-tag.before')).toHaveText('b')
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 const name=page.locator('.project-name input')
 await name.focus();await page.keyboard.press('Space')
 await expect(dialog).toHaveCount(0)
})
