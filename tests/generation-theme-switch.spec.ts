import {test,expect} from '@playwright/test'
test('generation borders follow repeated live theme switches',async({page})=>{
 await page.route('**/api/skills/images/tasks/**',r=>r.fulfill({json:{id:r.request().url().split('/').at(-1),status:r.request().url().endsWith('-1')?'failed':r.request().url().endsWith('-2')?'connection_lost':'running',message:'测试处理中',createdAt:new Date().toISOString(),images:[]}}))
 await page.setViewportSize({width:1440,height:1100})
 await page.goto('/')
 await page.getByRole('button',{name:'切换深色主题'}).click()
 const nodes=['running','failed','connection_lost'].map((status,i)=>({id:'theme-'+i,type:'card',position:{x:120+i*390,y:180},style:{width:340,height:400},data:{kind:'image',imagePresentationVersion:1,label:'图像',imageJob:{id:'mock-'+i,status,message:'测试状态',createdAt:new Date().toISOString()},pendingResult:{jobId:'mock-'+i,sourceNode:'theme-'+i,index:0,endpoint:'images'}}}))
 const previewSrc=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=300;c.height=200;const ctx=c.getContext('2d')!;ctx.fillStyle='#827567';ctx.fillRect(0,0,300,200);return c.toDataURL()})
 const previewNodes=['running','failed','connection_lost'].map((status,i)=>({id:'preview-theme-'+i,type:'card',position:{x:120+i*390,y:650},style:{width:340,height:227},data:{kind:'image',src:previewSrc,imagePresentationVersion:1,label:'预览',canvasOperation:'edit',imageJob:{id:'preview-mock-'+i,status,message:'测试状态',createdAt:new Date().toISOString()}}}))
 await page.locator('input[accept=".visproj"]').setInputFiles({name:'themes.visproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'visproj',schemaVersion:1,name:'主题切换检查',nodes:[...nodes,...previewNodes],edges:[],viewport:{x:0,y:0,zoom:1}}))})
 const loading=page.locator('[data-id="theme-0"]>.result-placeholder')
 await expect(loading).toBeVisible()
 expect(await loading.evaluate(el=>getComputedStyle(el,'::before').animationDuration)).toBe('2s')
 for(let i=0;i<3;i++){
  await page.getByRole('button',{name:'切换浅色主题'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  await page.waitForTimeout(450)
  await expect(page.locator('[data-id="theme-1"] .canvas-generation-failure')).toBeVisible()
  await expect(page.locator('[data-id="preview-theme-1"] .preview-failed')).toBeVisible()
  const color=await loading.evaluate(el=>getComputedStyle(el).borderTopColor)
  expect(color).not.toBe('rgb(59, 66, 78)')
  const shadow=await loading.evaluate(el=>getComputedStyle(el).boxShadow)
  expect(shadow).not.toMatch(/rgba?\(0, 0, 0[,)]/)
  await loading.evaluate(el=>{for(const a of el.getAnimations({subtree:true})){if((a as CSSAnimation).animationName==='generation-shimmer'){a.pause();a.currentTime=Number(a.effect!.getTiming().duration)/2}}})
  await page.screenshot({path:'test-results/theme-switch-light.png'})
  await loading.evaluate(el=>{for(const a of el.getAnimations({subtree:true})){if((a as CSSAnimation).animationName==='generation-shimmer')a.play()}})
  await page.getByRole('button',{name:'切换深色主题'}).click()
  await page.waitForTimeout(450)
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await expect(loading).toHaveCSS('border-top-color','rgb(59, 66, 78)')
  await loading.evaluate(el=>{for(const a of el.getAnimations({subtree:true})){if((a as CSSAnimation).animationName==='generation-shimmer'){a.pause();a.currentTime=Number(a.effect!.getTiming().duration)/2}}})
  await page.screenshot({path:'test-results/theme-switch-dark.png'})
  await loading.evaluate(el=>{for(const a of el.getAnimations({subtree:true})){if((a as CSSAnimation).animationName==='generation-shimmer')a.play()}})
  for(let j=0;j<3;j++){
   const node=page.locator('[data-id="preview-theme-'+j+'"]')
   await expect(node.locator('.generation-overlay')).toHaveCSS('border-radius','16px')
   await expect(node.locator('.generation-overlay')).toHaveCSS('overflow','hidden')
  }
 }
})
