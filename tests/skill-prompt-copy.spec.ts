import {test,expect} from '@playwright/test'
test('skill result prompt supports native copy, cut and paste with an image selected',async({page,context})=>{
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 await page.goto('/')
 const src=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=200;c.height=200;return c.toDataURL()})
 const project={format:'visproj',schemaVersion:1,name:'技能文本测试',nodes:[{id:'result',type:'card',position:{x:450,y:150},style:{width:240,height:240},data:{kind:'image',label:'材质结果',src,imagePresentationVersion:1,tool:'material',skillResult:{sourceNode:'missing',review:{}},iterationContext:{tool:'material',prompt:'保留构图，只更换墙面材质。'}}}],edges:[],viewport:{x:0,y:0,zoom:1}}
 await page.locator('input[accept=".visproj"]').setInputFiles({name:'prompt.visproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
 await page.locator('.react-flow__node[data-id="result"] .image-body').click()
 const expand=page.getByRole('button',{name:'展开创作面板'});if(await expand.isVisible())await expand.click()
 await page.getByRole('button',{name:'沿用技能',exact:true}).click()
 const input=page.getByRole('textbox',{name:'结果补充说明'})
 await input.fill('保留构图，只更换墙面材质。')
 await input.press('Control+a');await input.press('Control+c')
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe('保留构图，只更换墙面材质。')
 await input.press('Control+x');await expect(input).toHaveValue('')
 await input.press('Control+v');await expect(input).toHaveValue('保留构图，只更换墙面材质。')
 await input.evaluate((el:HTMLTextAreaElement)=>el.setSelectionRange(0,4))
 await input.press('Control+c')
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe('保留构图')
 await expect(page.getByRole('button',{name:'复制提示词'})).toHaveCount(0)
 await expect(page.locator('.refine-editor-caption')).toHaveCount(0)
 const focusStyle=await input.evaluate(el=>({outline:getComputedStyle(el).outlineStyle,border:getComputedStyle(el).borderTopWidth,padding:getComputedStyle(el.parentElement!).paddingTop,radius:getComputedStyle(el.parentElement!).borderRadius}))
 expect(focusStyle).toEqual({outline:'none',border:'0px',padding:'10px',radius:'12px'})
 await page.screenshot({path:'artifacts/skill-prompt-light.png'})
 await page.getByRole('button',{name:'切换深色主题'}).click()
 await page.screenshot({path:'artifacts/skill-prompt-dark.png'})
 await expect(page.locator('.react-flow__node[data-id="result"]')).toHaveCount(1)
})
