import {test,expect} from '@playwright/test'

const src='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='

test('点击编辑后才可在原图框选多个区域，并把坐标与说明一次提交',async({page})=>{
 const requests:any[]=[]
 await page.route('**/api/skills/canvas/tasks',async route=>{
  const body=route.request().postDataJSON();requests.push(body)
  await route.fulfill({json:{id:body.requestId,status:'queued',message:'测试已拦截',createdAt:new Date().toISOString()}})
 })
 await page.goto('/')
 const project={format:'visproj',schemaVersion:1,name:'交互编辑测试',viewport:{x:0,y:0,zoom:1},edges:[],nodes:[{id:'base',type:'card',position:{x:320,y:200},style:{width:300,height:200},data:{kind:'image',src,label:'原图',dimensions:'1 × 1',imagePresentationVersion:1}}]}
 await page.locator('input[accept=".visproj"]').setInputFiles({name:'interactive-edit.visproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
 await expect(page.locator('.interactive-edit-overlay')).toHaveCount(0)
 await page.locator('[data-id="base"] .image-body').click()
 await page.getByRole('toolbar',{name:'图片快捷修改'}).getByRole('button',{name:'编辑',exact:true}).click()
 const overlay=page.locator('.interactive-edit-overlay')
 await expect(overlay).toBeVisible()
 await expect.poll(async()=>(await overlay.boundingBox())?.width).toBeLessThan(205)
 const rect=await overlay.boundingBox();expect(rect).not.toBeNull()
 const card=await page.locator('[data-id="base"]').boundingBox();expect(card).not.toBeNull()
 expect(rect!.width).toBeCloseTo(200,0)
 expect(rect!.x-card!.x).toBeCloseTo(50,0)
 const draw=async([x1,y1,x2,y2]:number[])=>{
  await page.mouse.move(rect!.x+rect!.width*x1,rect!.y+rect!.height*y1)
  await page.mouse.down()
  await page.mouse.move(rect!.x+rect!.width*x2,rect!.y+rect!.height*y2,{steps:5})
  await page.mouse.up()
 }
 const promptField=page.getByRole('textbox',{name:'图片修改要求'})
 await draw([.1,.2,.45,.55])
 await expect(promptField.locator('.interactive-edit-mention')).toHaveCount(1)
 await page.getByRole('button',{name:'添加或管理框选区域'}).click()
 await page.getByRole('menuitemcheckbox',{name:'引用区域 1'}).click()
 await expect(promptField.locator('.interactive-edit-mention')).toHaveCount(0)
 await draw([.58,.15,.82,.4])
 await page.keyboard.type('去掉')
 await draw([.36,.58,.7,.82])
 await page.keyboard.type('改成蓝色')
 await expect(overlay.locator('.interactive-edit-box')).toHaveCount(3)
 await expect(promptField.locator('input')).toHaveCount(0)
 const mentions=promptField.locator('.interactive-edit-mention')
 await expect(mentions).toHaveCount(2)
 const firstMention=await mentions.nth(0).boundingBox(),secondMention=await mentions.nth(1).boundingBox()
 expect(Math.abs(firstMention!.y-secondMention!.y)).toBeLessThan(2)
 await page.getByRole('button',{name:'添加或管理框选区域'}).click()
 await page.getByRole('menuitemcheckbox',{name:'引用区域 1'}).click()
 await page.keyboard.type('保持原样')
 await expect(mentions).toHaveCount(3)
 await page.getByRole('button',{name:'添加或管理框选区域'}).click()
 await page.getByRole('menuitemcheckbox',{name:'引用区域 1'}).click()
 await expect(mentions).toHaveCount(2)
 await expect(promptField).not.toContainText('保持原样')
 await page.getByRole('button',{name:'切换深色主题'}).click()
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
 await expect.poll(async()=>Number((await page.getByRole('button',{name:'撤销框选'}).evaluate(button=>getComputedStyle(button).backgroundColor)).match(/\d+/)?.[0])).toBeLessThan(100)
 await expect.poll(async()=>Number((await promptField.evaluate(field=>getComputedStyle(field).backgroundColor)).match(/\d+/)?.[0])).toBeLessThan(100)
 await expect.poll(async()=>Number((await page.locator('.interactive-edit-bar').evaluate(bar=>getComputedStyle(bar).backgroundColor)).match(/\d+/)?.[0])).toBeLessThan(100)
 await page.getByRole('button',{name:'生成图片'}).click()
 await expect.poll(()=>requests.length).toBe(1)
 expect(requests[0].operation).toBe('edit')
 expect(requests[0].parameters.prompt).toMatch(/区域 2：\s*去掉\s+区域 3：\s*改成蓝色/)
 expect(requests[0].parameters.prompt).not.toContain('区域 1：')
 const boxes=requests[0].parameters.boxes
 expect(boxes).toHaveLength(3)
 expect(boxes[0][0]).toBeGreaterThan(70);expect(boxes[0][0]).toBeLessThan(130)
 expect(boxes[0][2]).toBeGreaterThan(420);expect(boxes[0][2]).toBeLessThan(480)
 expect(boxes[1][0]).toBeGreaterThan(550);expect(boxes[1][0]).toBeLessThan(620)
})
