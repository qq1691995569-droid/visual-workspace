import { test, expect } from '@playwright/test'

const pixel = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64')

test('图片 → 拖线创建工具 → 保存恢复 → 导出导入', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: '展开工具面板', exact: true }).click()
  await expect(page.getByText('把想象，连接成画面。')).toBeVisible()
  await page.locator('input[type=file]').first().setInputFiles({ name: 'product.png', mimeType: 'image/png', buffer: pixel })
  await expect(page.locator('.image-body img')).toBeVisible()
  const handle = await page.locator('.react-flow__handle-right').boundingBox()
  if (!handle) throw Error('未找到连接点')
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + 180, handle.y + 120, { steps: 20 })
  await page.mouse.up()
  await expect(page.locator('.tool-menu')).toBeVisible()
  await page.locator('.tool-menu').getByRole('button', { name: /材质优化/ }).click()
  await expect(page.locator('.react-flow__edge')).toHaveCount(1)
  await page.locator('.tool-body textarea').fill('保留产品，柜面替换成浅胡桃木')
  await page.getByRole('button', { name: '检查运行条件' }).click()
  await expect(page.getByRole('status')).toContainText('执行服务尚未接入')
  await page.getByRole('textbox', { name: '项目名称' }).fill('测试项目')
  await expect(page.getByText('● 已保存在此浏览器', { exact: true })).toBeVisible()
  await page.waitForTimeout(1000)
  await page.reload()
  await expect(page.locator('.tool-body textarea')).toHaveValue('保留产品，柜面替换成浅胡桃木')
  await expect(page.locator('.react-flow__edge')).toHaveCount(1)
  await expect(page.locator('.image-body img')).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出项目' }).click()
  const file = await downloaded
  expect(file.suggestedFilename()).toBe('测试项目.visproj')
  const path = await file.path()
  if (!path) throw Error('导出文件缺失')
  await page.getByRole('textbox', { name: '项目名称' }).fill('临时修改')
  page.once('dialog', dialog => dialog.accept())
  await page.locator('input[type=file]').nth(1).setInputFiles(path)
  await expect(page.getByRole('textbox', { name: '项目名称' })).toHaveValue('测试项目')
  await expect(page.locator('.tool-body textarea')).toHaveValue('保留产品，柜面替换成浅胡桃木')
  await page.screenshot({ path: 'test-results/canvas.png', fullPage: true })
  expect(errors).toEqual([])
})

test('空工具提示缺少输入，损坏的项目不覆盖画布', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '展开工具面板', exact: true }).click()
  await page.getByRole('button', { name: /材质优化 保留结构/ }).click()
  await page.getByRole('button', { name: '检查运行条件' }).click()
  await expect(page.getByRole('status')).toContainText('请先连接一张输入图片')
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'bad.visproj', mimeType: 'application/json', buffer: Buffer.from('{"format":"unknown"}') })
  await expect(page.getByRole('status')).toContainText('不支持的项目文件')
  await expect(page.locator('.react-flow__node')).toHaveCount(1)
})
