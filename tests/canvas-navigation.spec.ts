import {test,expect} from '@playwright/test'

test('选择箭头与中键临时平移，松开恢复选择且不移动节点',async({page})=>{
 await page.goto('/')
 await expect(page.locator('.react-flow__pane')).toBeVisible()
 await expect(page.getByRole('button',{name:'抓手工具',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'选择工具',exact:true}).click()
 const pane=page.locator('.react-flow__pane'),viewport=page.locator('.react-flow__viewport')
 await expect(pane).toHaveCSS('cursor',/select\.svg/)
 const before=await viewport.getAttribute('style')
 await page.mouse.move(1000,400);await page.mouse.down({button:'middle'})
 await expect(pane).toHaveCSS('cursor','grabbing')
 await page.mouse.move(1110,460,{steps:8});await page.mouse.up({button:'middle'})
 await expect(pane).toHaveCSS('cursor',/select\.svg/)
 expect(await viewport.getAttribute('style')).not.toBe(before)
 const after=await viewport.getAttribute('style')
 await page.mouse.move(1000,400);await page.mouse.down();await page.mouse.move(1100,500,{steps:6});await page.mouse.up()
 expect(await viewport.getAttribute('style')).toBe(after)
 const pixel=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')
 await page.locator('input[type=file]').first().setInputFiles({name:'test.png',mimeType:'image/png',buffer:pixel})
 const node=page.locator('.react-flow__node-card').first()
 await expect(node).toBeVisible()
 const pos=await node.getAttribute('style'),box=await node.boundingBox()
 if(!box)throw Error('Missing node')
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down({button:'middle'});await page.mouse.move(box.x+box.width/2+70,box.y+box.height/2+40,{steps:8});await page.mouse.up({button:'middle'})
 expect(await node.getAttribute('style')).toBe(pos)
 await expect(pane).toHaveCSS('cursor',/select\.svg/)
})
