import {test, expect} from '@playwright/test'

test('只有修饰键点击添加参考，普通选择不打开面板且参考保持稳定', async ({page}) => {
  const submissions: Record<string, unknown>[] = []
  await page.route('**/api/skills/images/tasks', async route => {
    submissions.push(route.request().postDataJSON())
    await route.fulfill({json:{id:'composer-test',status:'paused',message:'模拟提交'}})
  })
  await page.route('**/api/skills/images/tasks/composer-test', route => route.fulfill({json:{id:'composer-test',status:'paused',message:'模拟提交',images:[]}}))
  await page.goto('/')
  const src = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='
  const secondSrc = await page.evaluate(()=>{const c=document.createElement('canvas');c.width=c.height=2;return c.toDataURL()})
  const project = {format:'visproj',schemaVersion:1,name:'创作切换测试',viewport:{x:0,y:0,zoom:1},edges:[],nodes:[
    {id:'result',type:'card',position:{x:420,y:170},style:{width:250,height:180},data:{kind:'image',label:'材质优化结果',src,dimensions:'1 × 1',skillResult:{jobId:'old',sourceNode:'removed-source',review:{}},iterationContext:{tool:'material',prompt:'旧技能提示词',referenceIds:[],options:{model:'old-model',resolution:'2K',ratio:'auto',count:2}}}},
    {id:'reference',type:'card',position:{x:720,y:170},style:{width:200,height:180},data:{kind:'image',label:'第二张参考',src:secondSrc}},
  ]}
  await page.locator('input[accept=".visproj"]').setInputFiles({name:'composer.visproj',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await page.locator('.react-flow__node[data-id="result"] .image-body').click()
  await expect(page.locator('.creation-dock')).toHaveClass(/minimized/)
  await expect(page.getByRole('toolbar',{name:'图片快捷修改'})).toBeVisible()
  await page.getByRole('button',{name:'展开创作面板',exact:true}).click()
  await page.getByLabel('创作提示词').fill('让画面更明亮')
  await page.locator('.react-flow__node[data-id="result"] .image-body').click({modifiers:['Control']})
  await expect(page.getByRole('toolbar',{name:'图片快捷修改'})).toBeVisible()
  await expect(page.getByRole('toolbar',{name:'图片快捷修改'}).getByRole('button',{name:'提取资产',exact:true})).toBeVisible()
  await expect(page.getByLabel('创作提示词')).toHaveValue('让画面更明亮')
  await expect(page.locator('.creation-dock .reference-strip')).toContainText('材质优化结果')
  await expect(page.locator('.creation-modes button.chosen')).toHaveText('图生图')
  await expect(page.locator('.refine-heading')).toHaveCount(0)
  await page.getByRole('button',{name:'收起创作面板',exact:true}).click()
  await expect(page.locator('.refine-heading')).toHaveCount(0)
  await page.getByRole('button',{name:'展开创作面板',exact:true}).click()
  await page.keyboard.down('Shift')
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click()
  await page.keyboard.up('Shift')
  await expect(page.getByRole('toolbar',{name:'图片快捷修改'})).toHaveCount(0)
  await expect(page.locator('.reference-strip>span')).toHaveCount(1)
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click({modifiers:['Control']})
  await expect(page.locator('.reference-strip>span')).toHaveCount(2)
  await expect(page.locator('.reference-strip>span').nth(0)).toContainText('图1')
  await expect(page.locator('.reference-strip>span').nth(1)).toContainText('图2')
  await expect(page.getByLabel('创作提示词')).toHaveValue('让画面更明亮')
  await page.mouse.click(1050,400)
  await expect(page.locator('.reference-strip>span')).toHaveCount(2)
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click()
  await expect(page.locator('.reference-strip>span').nth(0)).toContainText('材质优化结果')
  await page.locator('.reference-strip>span').nth(1).hover()
  await page.getByRole('button',{name:'前移图2',exact:true}).click()
  await expect(page.locator('.reference-strip>span').nth(0)).toContainText('第二张参考')
  await page.locator('.reference-strip>span').nth(0).hover()
  await page.getByRole('button',{name:'后移图1',exact:true}).click()
  await page.getByRole('button',{name:'移除图2',exact:true}).click()
  await expect(page.locator('.reference-strip>span')).toHaveCount(1)
  await page.mouse.click(1050,400)
  await expect(page.locator('.reference-strip>span')).toHaveCount(1)
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click()
  await expect(page.locator('.reference-strip>span')).toHaveCount(1)
  await page.getByRole('button',{name:'收起创作面板',exact:true}).click()
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click()
  await expect(page.locator('.creation-dock')).toHaveClass(/minimized/)
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click({modifiers:['Meta']})
  await expect(page.locator('.reference-strip>span')).toHaveCount(2)
  await page.locator('.react-flow__node[data-id="reference"] .image-body').click({modifiers:['Control']})
  await expect(page.locator('.reference-strip>span')).toHaveCount(2)
  await page.screenshot({path:'artifacts/explicit-composer-references.png'})
  await expect(page.locator('.project-name')).toContainText('已保存在此浏览器')
  await page.reload()
  await page.getByRole('button',{name:'展开创作面板',exact:true}).click()
  await expect(page.locator('.reference-strip>span')).toHaveCount(2)
  await expect(page.locator('.reference-strip>span').nth(0)).toContainText('材质优化结果')
  await expect(page.getByLabel('创作提示词')).toHaveValue('让画面更明亮')
  await page.locator('.dock-submit').click()
  await expect.poll(()=>submissions.length).toBe(1)
  expect(submissions[0]).toMatchObject({mode:'redraw',prompt:'让画面更明亮',images:[src,secondSrc]})
  expect(submissions[0]).not.toHaveProperty('edit')
})
